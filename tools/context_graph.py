class GraphError(Exception):
    """An actionable source or output error."""


@dataclass(frozen=True)
class CodeFile:
    path: str
    language: str
    size: int


@dataclass(frozen=True)
class Module:
    path: str
    name: str | None
    symbols: tuple[str, ...]
    imports: tuple[str | None, ...]


@dataclass(frozen=True)
class RepositoryMap:
    files: tuple[CodeFile, ...]
    modules: tuple[Module, ...]
    roots: tuple[str, ...]
    ambiguous: tuple[str, ...]
    parse_errors: tuple[str, ...]


def _inside(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
        return True
    except ValueError:
        return False


def _module_name(path: Path, root: Path) -> str | None:
    parts = list(path.relative_to(root).parts)
    if parts and parts[-1] == "__init__.py":
        parts.pop()
    elif parts:
        parts[-1] = Path(parts[-1]).stem
    if not parts or any(not part.isidentifier() for part in parts):
        return None
    return ".".join(parts)


def _roots(project: Path, requested: Sequence[Path] | None) -> tuple[Path, ...]:
    roots: set[Path] = set()
    for source in requested or (Path("."),):
        candidate = source if source.is_absolute() else project / source
        try:
            root = candidate.resolve(strict=True)
        except OSError as error:
            raise GraphError(f"cannot resolve source root '{source}': {error}") from error
        if not root.is_dir() or not _inside(root, project):
            raise GraphError(f"source root must be a directory inside --root: {source}")
        roots.add(root)
    return tuple(sorted(roots, key=lambda item: (len(item.parts), item.as_posix())))


def _language_for(path: Path) -> str | None:
    return SPECIAL_FILES.get(path.name) or LANGUAGE_BY_SUFFIX.get(path.suffix.lower())


def _scan_files(project: Path, roots: Sequence[Path], limit: int) -> tuple[CodeFile, ...]:
    found: dict[Path, str] = {}

    def scan_error(error: OSError) -> None:
        raise GraphError(f"cannot scan '{error.filename}': {error.strerror or error}") from error

    for root in roots:
        for current, directories, names in os.walk(root, followlinks=False, onerror=scan_error):
            folder = Path(current)
            directories[:] = sorted(
                name
                for name in directories
                if name not in EXCLUDED_DIRS and not (folder / name).is_symlink()
            )
            for name in names:
                path = folder / name
                if path.is_symlink():
                    continue
                language = _language_for(path)
                if language:
                    found[path] = language
                    if len(found) > limit:
                        raise GraphError(
                            f"code file limit exceeded ({limit}); narrow --source or raise --max-files"
                        )
    if not found:
        raise GraphError("no recognized code files in the selected roots")
    files: list[CodeFile] = []
    for path, language in sorted(found.items(), key=lambda item: item[0].as_posix()):
        try:
            size = path.stat().st_size
        except OSError:
            size = 0
        files.append(CodeFile(path.relative_to(project).as_posix(), language, size))
    return tuple(files)


def _owner(path: Path, roots: Sequence[Path]) -> Path:
    return max((root for root in roots if _inside(path, root)), key=lambda root: len(root.parts))


def _imports(
    tree: ast.Module,
    name: str | None,
    is_package: bool,
    module_names: set[str],
) -> tuple[str | None, ...]:
    imports: set[str | None] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imports.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            parts = name.split(".") if name else []
            if not is_package and parts:
                parts.pop()
            ascents = node.level - 1
            valid = ascents < len(parts)
            if valid and ascents:
                parts = parts[:-ascents]
            if node.module:
                parts.extend(node.module.split("."))
            base = ".".join(parts) if valid else ""
            if node.level == 0:
                base = node.module or ""
            if not valid or not base:
                imports.add(None)
                continue
            child = next(
                (f"{base}.{alias.name}" for alias in node.names
                 if alias.name != "*" and f"{base}.{alias.name}" in module_names),
                None,
            )
            imports.add(child or base)
    return tuple(sorted(imports, key=lambda value: value or ""))


def _symbols(tree: ast.Module) -> tuple[str, ...]:
    symbols: list[str] = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef):
            methods = [
                item.name
                for item in node.body
                if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef))
            ]
            if len(methods) > MAX_METHODS:
                methods = [*methods[:MAX_METHODS], f"+{len(methods) - MAX_METHODS} more"]
            suffix = f" ({', '.join(methods)})" if methods else ""
            line_end = getattr(node, "end_lineno", node.lineno)
            symbols.append(f"class {node.name} L{node.lineno}-L{line_end}{suffix}")
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            kind = "async function" if isinstance(node, ast.AsyncFunctionDef) else "function"
            line_end = getattr(node, "end_lineno", node.lineno)
            symbols.append(f"{kind} {node.name} L{node.lineno}-L{line_end}")
    return tuple(symbols)


def _python_modules(project: Path, roots: Sequence[Path], files: Sequence[CodeFile]) -> tuple[tuple[Module, ...], tuple[str, ...], tuple[str, ...]]:
    paths = [project / item.path for item in files if item.language == "Python"]
    if not paths:
        return (), (), ()
    raw_names = {path: _module_name(path, _owner(path, roots)) for path in paths}
    counts = Counter(name for name in raw_names.values() if name)
    ambiguous = tuple(sorted(name for name, count in counts.items() if count > 1))
    names = {
        path: (name if name and counts[name] == 1 else None)
        for path, name in raw_names.items()
    }
    module_names = {name for name in names.values() if name}
    modules: list[Module] = []
    errors: list[str] = []
    for path in paths:
        relative = path.relative_to(project).as_posix()
        name = names[path]
        try:
            with tokenize.open(path) as stream:
                tree = ast.parse(stream.read(), filename=str(path))
        except (OSError, UnicodeError, SyntaxError, ValueError) as error:
            detail = f"{error.msg} at line {error.lineno}" if isinstance(error, SyntaxError) else str(error)
            errors.append(f"{relative}: {detail}")
            modules.append(Module(relative, name, (), ()))
            continue
        modules.append(Module(
            path=relative,
            name=name,
            symbols=_symbols(tree),
            imports=_imports(tree, name, path.name == "__init__.py", module_names),
        ))
    return tuple(modules), ambiguous, tuple(errors)


def build_repository(
    project_root: Path,
    source_roots: Sequence[Path] | None = None,
    max_files: int = MAX_FILES,
) -> RepositoryMap:
    if max_files < 1:
        raise GraphError("--max-files must be positive")
    try:
        project = project_root.expanduser().resolve(strict=True)
    except OSError as error:
        raise GraphError(f"cannot resolve project root '{project_root}': {error}") from error
    if not project.is_dir():
        raise GraphError(f"project root is not a directory: {project}")

    roots = _roots(project, source_roots)
    files = _scan_files(project, roots, max_files)
    modules, ambiguous, parse_errors = _python_modules(project, roots, files)
    labels = [
        "." if root == project else root.relative_to(project).as_posix()
        for root in roots
    ]
    return RepositoryMap(files, modules, tuple(labels), ambiguous, parse_errors)


def _directory_map(files: Sequence[CodeFile]) -> list[tuple[str, int, Counter[str]]]:
    folders: dict[str, Counter[str]] = {}
    for item in files:
        folder = item.path.rsplit("/", 1)[0] if "/" in item.path else "."
        folders.setdefault(folder, Counter())[item.language] += 1
    return sorted(
        ((folder, sum(counts.values()), counts) for folder, counts in folders.items()),
        key=lambda item: (item[0].count("/"), item[0]),
    )


def render_repository_map(
    repo: RepositoryMap,
    max_chars: int = MAX_CHARS,
    include_files: bool = False,
    include_external_imports: bool = False,
) -> str:
    if max_chars < 1:
        raise GraphError("--max-output-chars must be positive")
    languages = Counter(item.language for item in repo.files)
    sizes = Counter()
    for item in repo.files:
        sizes[item.language] += item.size
    lines = [
        MARKER,
        "# Repository Context Map",
        f"Source roots: {', '.join(f'`{root}`' for root in repo.roots)}",
        f"Files: {len(repo.files)}",
        "",
        "## Languages",
    ]
    for language, count in sorted(languages.items(), key=lambda item: (-item[1], item[0])):
        lines.append(f"- {language}: {count} files, {sizes[language]:,} bytes")
    lines.extend(["", "## Directory Map"])
    directories = _directory_map(repo.files)
    for folder, count, counts in directories[:MAX_DIRS]:
        summary = ", ".join(f"{language} {amount}" for language, amount in counts.most_common(3))
        label = "(root)" if folder == "." else folder + "/"
        lines.append(f"- `{label}`: {count} files ({summary})")
    if len(directories) > MAX_DIRS:
        lines.append(f"- ... {len(directories) - MAX_DIRS} more directories")
    if repo.modules:
        lines.extend(["", "## Python Modules"])
        for module in repo.modules[:MAX_MODULES]:
            name = f" `{module.name}`" if module.name else " (not import-resolvable)"
            symbols = "; ".join(module.symbols[:MAX_SYMBOLS]) or "(no top-level definitions)"
            if len(module.symbols) > MAX_SYMBOLS:
                symbols += f"; +{len(module.symbols) - MAX_SYMBOLS} more"
            lines.append(f"- `{module.path}`{name}: {symbols}")
        if len(repo.modules) > MAX_MODULES:
            lines.append(f"- ... {len(repo.modules) - MAX_MODULES} more Python modules; narrow --source")
        lines.extend(["", "## Python Imports"])
        resolved = {module.name: module.path for module in repo.modules if module.name}
        external = 0
        for module in repo.modules[:MAX_MODULES]:
            for imported in module.imports:
                target = resolved.get(imported) if imported else None
                if target:
                    lines.append(f"- `{module.path}` -> `{imported}` [in-scope: `{target}`]")
                elif include_external_imports:
                    lines.append(f"- `{module.path}` -> `{imported or 'unresolved relative import'}` [external/outside scope]")
                else:
                    external += 1
        if external and not include_external_imports:
            lines.append(f"- {external} external/out-of-scope imports omitted; use --all-imports.")
    else:
        lines.extend(["", "## Python Modules", "- None detected; structural inventory only."])
    if repo.ambiguous:
        lines.extend(["", "## Ambiguous Python Modules", *(
            f"- `{name}` appears more than once; imports using it are left unresolved."
            for name in repo.ambiguous
        )])
    if repo.parse_errors:
        lines.extend(["", "## Python Parse Errors", *(f"- {error}" for error in repo.parse_errors)])
    if include_files:
        lines.extend(["", "## Files", *(f"- `{item.path}` ({item.language})" for item in repo.files)])
    lines.extend([
        "",
        "## Notes",
        "- Python symbols and imports are syntax-only; external imports are omitted unless --all-imports is set.",
        "- Other languages are a structural inventory, not a semantic dependency graph.",
        "- Verify source before relying on this map.",
    ])
    output = "\n".join(lines) + "\n"
    if len(output) > max_chars:
        raise GraphError(f"map exceeds --max-output-chars={max_chars}; narrow roots, omit --files, or raise the limit")
    return output


def write_graph(project: Path, content: str, force: bool = False) -> tuple[Path, bool]:
    destination = project / ".hase" / "context.md"
    if destination.exists():
        try:
            existing = destination.read_text(encoding="utf-8")
        except (OSError, UnicodeError) as error:
            raise GraphError(f"cannot read '{destination}': {error}") from error
        if existing.splitlines()[:1] != [MARKER] and not force:
            raise GraphError(f"refusing to replace handwritten '{destination}'; review and use --force")
        if existing == content:
            return destination, False

    temporary: Path | None = None
    try:
        destination.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=destination.parent,
                                         prefix=".context-", suffix=".tmp", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(content)
        os.replace(temporary, destination)
    except OSError as error:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
        raise GraphError(f"cannot write '{destination}': {error}") from error
    return destination, True


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate a compact local context map for any codebase.")
    parser.add_argument("--root", type=Path, default=Path("."))
    parser.add_argument("--source", type=Path, action="append", default=None)
    parser.add_argument("--max-files", type=int, default=MAX_FILES)
    parser.add_argument("--max-output-chars", type=int, default=MAX_CHARS)
    parser.add_argument("--force", action="store_true", help="replace non-generated context after review")
    parser.add_argument("--files", action="store_true", help="include the full code-file listing")
    parser.add_argument("--all-imports", action="store_true", help="include external and out-of-scope Python imports")
    args = parser.parse_args(argv)
    try:
        root = args.root.expanduser().resolve(strict=True)
        repository = build_repository(root, args.source, args.max_files)
        content = render_repository_map(
            repository,
            args.max_output_chars,
            args.files,
            args.all_imports,
        )
        output, changed = write_graph(root, content, args.force)
    except (GraphError, OSError) as error:
        print(f"context_graph: error: {error}", file=sys.stderr)
        return 2
    print(
        f"context_graph: {'updated' if changed else 'up-to-date'} {output} "
        f"({len(repository.files)} files, {len(repository.modules)} Python modules, {len(content)} characters)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
